"""Releases (ADR-053 §3): what to build, and the manifest that pins it by digest.

    python3 scripts/release.py plan
        One JSON line per image: {"service", "context", "dockerfile", "target"}.
        Read from `infra/docker-compose.build.yml`, the same list a server uses to
        build locally, so CI and a hand build cannot drift apart.

    python3 scripts/release.py manifest --version 1.0.0 --registry ghcr.io/o/r \\
        --digests digests.json --out infra/release-1.0.0.yml
        Copies `infra/docker-compose.prod.yml` and replaces every
        `${ORPYCA_REGISTRY:?…}/<svc>:${ORPYCA_VERSION:?…}` with
        `<registry>/<svc>:<version>@sha256:…`. `digests.json` maps service to digest.
        Fails if an image is left without a digest. Comments and order are kept:
        the release file reads like the manifest it came from.

Standard library only: it runs on a bare CI runner.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROD = ROOT / "infra" / "docker-compose.prod.yml"
BUILD = ROOT / "infra" / "docker-compose.build.yml"
VERSION = re.compile(r"^\d+\.\d+\.\d+$")
DIGEST = re.compile(r"^sha256:[0-9a-f]{64}$")
PLACEHOLDER = re.compile(
    r"\$\{ORPYCA_REGISTRY(?::\?[^}]*)?\}/(?P<svc>[a-z0-9-]+):\$\{ORPYCA_VERSION(?::\?[^}]*)?\}"
)


def plan(build_file: Path = BUILD) -> list[dict[str, str]]:
    """Services with a `build:` in the override. Minimal YAML reading, no PyYAML."""
    entries: list[dict[str, str]] = []
    current: dict[str, str] | None = None
    in_services = False
    for raw in build_file.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].rstrip()
        if not line:
            continue
        if line == "services:":
            in_services = True
            continue
        if not in_services:
            continue
        if m := re.fullmatch(r"  ([a-z0-9-]+):", line):
            current = {"service": m[1], "context": "", "dockerfile": "Dockerfile", "target": ""}
            entries.append(current)
        elif current is not None and (m := re.fullmatch(r"      (context|dockerfile|target): (\S+)", line)):
            current[m[1]] = m[2]
    for e in entries:
        context = (build_file.parent / e["context"]).resolve()
        e["dockerfile"] = (context / e["dockerfile"]).relative_to(ROOT).as_posix()
        e["context"] = context.relative_to(ROOT).as_posix() or "."
    return entries


def manifest(version: str, registry: str, digests: dict[str, str], prod_file: Path = PROD) -> str:
    if not VERSION.match(version):
        raise SystemExit(f"version {version!r} is not X.Y.Z")
    bad = {s: d for s, d in digests.items() if not DIGEST.match(d)}
    if bad:
        raise SystemExit(f"not sha256 digests: {bad}")
    registry = registry.rstrip("/")
    missing: set[str] = set()

    def pin(m: re.Match[str]) -> str:
        svc = m["svc"]
        if svc not in digests:
            missing.add(svc)
            return m[0]
        return f"{registry}/{svc}:{version}@{digests[svc]}"

    text = PLACEHOLDER.sub(pin, prod_file.read_text(encoding="utf-8"))
    if missing:
        raise SystemExit(f"no digest for: {sorted(missing)}")
    if "ORPYCA_VERSION" in text or "ORPYCA_REGISTRY" in text:
        raise SystemExit("the release manifest still names ORPYCA_VERSION/ORPYCA_REGISTRY")
    header = (
        f"# release-{version}.yml — generated by scripts/release.py from infra/docker-compose.prod.yml.\n"
        f"# Every image of this release is pinned by digest. Do not edit: cut a new release.\n"
    )
    return header + text


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("plan")
    m = sub.add_parser("manifest")
    m.add_argument("--version", required=True)
    m.add_argument("--registry", required=True)
    m.add_argument("--digests", required=True, type=Path)
    m.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    if args.cmd == "plan":
        for entry in plan():
            print(json.dumps(entry))
        return 0
    digests = json.loads(args.digests.read_text(encoding="utf-8"))
    args.out.write_text(manifest(args.version, args.registry, digests), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
