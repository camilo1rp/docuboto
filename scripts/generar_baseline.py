"""Concatena las migraciones numeradas en un baseline. No se edita a mano.

Orden: auth → tenant → document → storage → workflow → archive → signature →
notification → knowledge. Primero `global/`, luego `tenant/`. El resultado vive
en `services/docuboto/migrations/{global,tenant}/001_baseline.sql`.
"""

from __future__ import annotations

import re
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[1]
DESTINO = RAIZ / "services" / "docuboto" / "migrations"
SERVICIOS = (
    "auth-service",
    "tenant-service",
    "document-service",
    "storage-service",
    "workflow-service",
    "archive-service",
    "signature-service",
    "notification-service",
    "knowledge-service",
)
_NUMERO = re.compile(r"^\d+_")
CABECERA = (
    "-- OrpycaMCP — Sistema de Gestión Documental Electrónico de Archivo (SGDEA).\n"
    "-- Desarrollo original de Orpyca; adaptado a partir de Orfeo bajo licencia GPL.\n"
    "-- GENERATED by scripts/generar_baseline.py. Do not edit.\n"
    "-- Source: services/*/migrations/{ambito}/*.sql in service order.\n\n"
)


def sql_files(directory: Path) -> list[Path]:
    if not directory.is_dir():
        return []
    return sorted(p for p in directory.glob("*.sql") if _NUMERO.match(p.name))


def concatenar(ambito: str) -> str:
    partes = [CABECERA.format(ambito=ambito)]
    for svc in SERVICIOS:
        for path in sql_files(RAIZ / "services" / svc / "migrations" / ambito):
            partes.append(f"-- >>> {svc}/{ambito}/{path.name}\n")
            partes.append(path.read_text(encoding="utf-8").rstrip())
            partes.append("\n\n")
    return "".join(partes)


def escribir(ambito: str) -> Path:
    dest = DESTINO / ambito / "001_baseline.sql"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(concatenar(ambito), encoding="utf-8")
    return dest


def main() -> None:
    for ambito in ("global", "tenant"):
        dest = escribir(ambito)
        print(f"{dest.relative_to(RAIZ)} ({dest.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
