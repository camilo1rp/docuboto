"""
OpenAPI aggregation router — combines specs from all downstream services
into a single OpenAPI 3.1.0 document for Swagger UI / ReDoc.

Each service exposes /openapi.json (auto-generated by FastAPI).
This gateway aggregates them with path remapping.
"""

import logging
from typing import Any

import httpx
from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse

logger = logging.getLogger(__name__)

router = APIRouter()

# Mapping of service names to (base_url, path_prefix)
_SERVICES = {
    "auth": ("auth_service_url", "/api/v1/auth"),
    "tenant": ("tenant_service_url", "/api/v1/tenants"),
    "document": ("document_service_url", "/api/v1/documents"),
    "archive": ("archive_service_url", "/api/v1/archive"),
    "storage": ("storage_service_url", "/api/v1/storage"),
    "workflow": ("workflow_service_url", "/api/v1/workflow"),
    "notification": ("notification_service_url", "/api/v1/notifications"),
}


async def _fetch_service_spec(client: httpx.AsyncClient, base_url: str) -> dict[str, Any] | None:
    """Fetch OpenAPI spec from a service, with fallback if unavailable."""
    try:
        resp = await client.get(f"{base_url}/openapi.json", timeout=5.0)
        if resp.status_code == 200:
            return resp.json()
    except Exception as exc:
        logger.warning(f"Failed to fetch spec from {base_url}: {exc}")
    return None


def _remap_paths(spec: dict[str, Any], prefix: str) -> dict[str, Any]:
    """
    Remap all paths in spec to include prefix.
    E.g., /token becomes /api/v1/auth/token
    """
    if "paths" not in spec:
        return spec

    remapped = {}
    for path, methods in spec["paths"].items():
        new_path = f"{prefix}{path}"
        remapped[new_path] = methods

    spec["paths"] = remapped
    return spec


def _merge_specs(base: dict[str, Any], additions: dict[str, Any]) -> dict[str, Any]:
    """
    Merge additional spec into base spec.
    - Paths are combined
    - Components (schemas) are merged with conflict resolution
    - Tags are combined
    """
    # Merge paths
    if "paths" in additions:
        if "paths" not in base:
            base["paths"] = {}
        base["paths"].update(additions["paths"])

    # Merge components (schemas, security schemes, etc.)
    if "components" in additions:
        if "components" not in base:
            base["components"] = {}
        for key, value in additions["components"].items():
            if key not in base["components"]:
                base["components"][key] = {}
            if isinstance(value, dict):
                base["components"][key].update(value)

    # Merge tags (avoid duplicates by tag name)
    if "tags" in additions:
        if "tags" not in base:
            base["tags"] = []
        existing_names = {t["name"] for t in base["tags"]}
        for tag in additions["tags"]:
            if tag.get("name") not in existing_names:
                base["tags"].append(tag)

    return base


@router.get("/api/v1/openapi.json", tags=["openapi"])
async def openapi_spec(request: Request) -> JSONResponse:
    """
    Aggregated OpenAPI 3.1.0 specification combining all downstream services.

    Returns a single spec with paths like:
    - /api/v1/auth/token
    - /api/v1/documents/
    - /api/v1/storage/upload
    - etc.

    Use with Swagger UI (https://swagger.io/tools/swagger-ui/)
    or ReDoc (https://redoc.ly/)
    """
    client: httpx.AsyncClient = request.app.state.http_client

    # Base spec — the gateway itself
    base_spec: dict[str, Any] = {
        "openapi": "3.1.0",
        "info": {
            "title": "OrpycaMCP API",
            "version": "1.0.0",
            "description": "Free, open-source Document Management System for Latin America",
            "license": {
                "name": "AGPL v3",
                "url": "https://www.gnu.org/licenses/agpl-3.0.html",
            },
            "contact": {
                "name": "OrpycaMCP Contributors",
                "url": "https://gitlab.com/orpyca/orpyca-mcp",
                "email": "aurigadl@gmail.com",
            },
        },
        "servers": [
            {
                "url": "http://localhost:8080",
                "description": "Development server",
            },
            {
                "url": "https://api.yourdomain.com",
                "description": "Production server (configure for your institution)",
            },
        ],
        "paths": {},
        "components": {
            "securitySchemes": {
                "bearerAuth": {
                    "type": "http",
                    "scheme": "bearer",
                    "bearerFormat": "JWT",
                    "description": "Bearer token from /api/v1/auth/token endpoint",
                }
            }
        },
        "tags": [
            {
                "name": "health",
                "description": "System health and status",
            },
            {
                "name": "auth",
                "description": "Authentication (Keycloak integration, JWT tokens)",
            },
            {
                "name": "tenants",
                "description": "Institution management and schema provisioning",
            },
            {
                "name": "documents",
                "description": "Document registration (radicación E/S/I)",
            },
            {
                "name": "archive",
                "description": "Expedientes, TRD, retention schedules",
            },
            {
                "name": "storage",
                "description": "File upload/download, presigned URLs, deduplication",
            },
            {
                "name": "workflow",
                "description": "Document routing (flujos), distribution tracking",
            },
            {
                "name": "notifications",
                "description": "Email alerts, notification history",
            },
        ],
    }

    # Fetch and merge specs from all services
    for service_name, (url_attr, path_prefix) in _SERVICES.items():
        base_url = getattr(request.app.state, url_attr, None)
        if not base_url:
            logger.warning(f"Service URL not configured: {url_attr}")
            continue

        spec = await _fetch_service_spec(client, base_url)
        if spec:
            # Remap paths to include prefix
            spec = _remap_paths(spec, path_prefix)
            # Merge into base
            base_spec = _merge_specs(base_spec, spec)
            logger.debug(f"Merged spec from {service_name} service")
        else:
            logger.warning(f"Could not fetch spec from {service_name} service at {base_url}")

    # Add gateway's own endpoints (health check)
    base_spec["paths"]["/health"] = {
        "get": {
            "summary": "Orchestrated health check",
            "description": "Check status of gateway and all downstream services",
            "tags": ["health"],
            "responses": {
                "200": {
                    "description": "All services healthy",
                    "content": {
                        "application/json": {
                            "schema": {
                                "type": "object",
                                "properties": {
                                    "status": {"type": "string", "example": "ok"},
                                    "checks": {"type": "object"},
                                },
                            }
                        }
                    },
                },
                "503": {
                    "description": "At least one service is degraded",
                },
            },
        }
    }

    return JSONResponse(content=base_spec)
