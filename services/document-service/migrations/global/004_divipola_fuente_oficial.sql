--     Alejandría figuraba en 05076, que no es su código.
--   * **18 códigos que DIVIPOLA no reconoce** — Sincelejo en el 15 (Boyacá),
--     Solano en 18765 en vez de 18756, corregimientos y veredas mezclados con
--     municipios: la basura acumulada de una instalación real.
--   * **5 municipios que faltaban**, incluidos dos posteriores al corte: Tuchín
--     (23815) y **Nuevo Belén de Bajirá** (27493), segregado de Riosucio e
--     incorporado por el DANE en 2023.
--
-- Los 33 departamentos sí coincidían: se habían escrito a mano contra la
-- denominación oficial, que es justamente lo que no se hizo con los municipios.
--
-- ── Por qué una migración nueva y no editar la 003 ──────────────────────────
--
-- El libro `public.schema_migrations` identifica cada migración por
-- `(servicio, nombre_archivo)` y **no guarda hash del contenido**: reescribir la
-- 003 dejaría a cualquier despliegue que ya la aplicó con el catálogo malo y sin
-- que nada avisara. Es el fallo mudo que este proyecto ya conoce.
