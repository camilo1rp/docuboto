/**
 * /admin/preservacion/api/sellos-archivo/resumen — Proxy SSR del resumen de
 * sellos de archivo (C-6): `GET /api/v1/signature/admin/sellos-archivo/resumen`
 * → { por_vencer, vencido, sin_revocacion, pendiente_worm, rechazado, margen_dias }.
 */

import { json } from "@sveltejs/kit";
import { API_V1 } from "$lib/utils/config.server.js";

/** @type {import('./$types').RequestHandler} */
export async function GET({ locals }) {
  const token = locals.accessToken ?? "";
  if (!token) {
    return json({ error: "unauthenticated", detail: "Sesión no válida." }, { status: 401 });
  }
  const tenant = locals.user?.tenant_slug ?? "";
  const userId = locals.user?.sub ?? "";
  /** @type {Record<string, string>} */
  const headers = { Authorization: `Bearer ${token}`, "X-Tenant-Slug": tenant };
  if (userId) headers["X-User-Id"] = userId;

  try {
    const res = await fetch(`${API_V1}/signature/admin/sellos-archivo/resumen`, { headers });
    const data = await res.json().catch(() => ({}));
    return json(data, { status: res.status });
  } catch {
    return json(
      { error: "connection_error", detail: "No se pudo consultar el resumen de sellos." },
      { status: 503 },
    );
  }
}
